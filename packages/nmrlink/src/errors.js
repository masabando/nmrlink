export const ERROR_CODES = Object.freeze(Object.fromEntries(Object.keys(messages).map(code => [code, code])));

export function createError(Type, code, details = {}, options = {}) {
  const message = messages[code].replace(/\{(\w+)\}/g, (token, key) => String(details[key] ?? token));
  const error = Type === AggregateError
    ? new AggregateError(options.errors, message, options.cause === undefined ? undefined : { cause: options.cause })
    : new Type(message, options.cause === undefined ? undefined : { cause: options.cause });
  error.code = code;
  error.details = { ...details };
  return error;
}

export function normalizeError(error, fallbackCode = "OPERATION_FAILED") {
  if (error && typeof error.code === "string" && Object.hasOwn(ERROR_CODES, error.code)) return error;
  const code = error?.name === "NotFoundError" ? "PORT_SELECTION_CANCELLED"
    : ["NotAllowedError", "SecurityError"].includes(error?.name) ? "SERIAL_PERMISSION_DENIED" : fallbackCode;
  return createError(Error, code, {}, { cause: error });
}

export function createWarning(code, details = {}) {
  const { message } = createError(Error, code, details);
  return { code, message, details: { ...details } };
}

export function warningFromError(error) {
  const diagnostic = normalizeError(error, "ANALYSIS_FAILED");
  return { code: diagnostic.code, message: diagnostic.message, details: { ...diagnostic.details } };
}
