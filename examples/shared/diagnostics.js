export function diagnosticMessage(diagnostic, locale = "ja") {
  const code = diagnostic?.code;
  if (!Object.hasOwn(japanese, code)) return null;
  if (locale === "en") return diagnostic.message;
  return japanese[code].replace(/\{(\w+)\}/g, (token, key) => String(diagnostic.details?.[key] ?? token));
}

export function uiError(error) {
  return diagnosticMessage(error) ?? error?.message ?? "処理に失敗しました。";
}

export function uiWarnings(result) {
  return result?.warningDetails
    ? result.warningDetails.map(warning => diagnosticMessage(warning) ?? warning.message).join(" ")
    : result?.warnings?.join(" ") ?? "";
}
